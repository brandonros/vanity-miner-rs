fn ethereum_test() -> EthereumVanityKeyResult {
    let request = EthereumVanityKeyRequest {
        prefix: b"",
        suffix: b"",
        thread_idx: THREAD_IDX,
        rng_seed: RNG_SEED,
    };
    generate_and_check_ethereum_vanity_key(&black_box(request))
}

checks! {
    /// secp256k1 uncompressed
    fn primitive_secp256k1_uncompressed() -> bool {
        secp256k1_derive_public_key_uncompressed(&black_box(SECP256K1_PRIVATE_KEY))
            == SECP256K1_UNCOMPRESSED_PUBLIC_KEY
    }

    /// keccak256 64bytes
    fn primitive_keccak256() -> bool {
        keccak256_64bytes(&black_box(KECCAK256_INPUT)) == KECCAK256_OUTPUT
    }

    /// ethereum priv
    fn private_key() -> bool {
        ethereum_test().private_key == PRIVATE_KEY
    }

    /// ethereum pub
    fn public_key() -> bool {
        ethereum_test().public_key == PUBLIC_KEY
    }

    /// ethereum address
    fn address() -> bool {
        ethereum_test().address == ADDRESS
    }

    /// ethereum candidate match payload
    fn candidate_match() -> bool {
        super::candidate::matches(
            candidate,
            RNG_SEED,
            THREAD_IDX,
            &ADDRESS[..2],
            &ADDRESS[18..],
            &PRIVATE_KEY,
        )
    }

    /// ethereum candidate suffix mismatch
    fn candidate_miss() -> bool {
        super::candidate::misses(candidate, RNG_SEED, THREAD_IDX, &ADDRESS[..2], &[0x65, 0x1d])
    }

    /// ethereum candidate invalid seed and pattern
    fn candidate_invalid() -> bool {
        super::candidate::rejects_invalid(candidate, RNG_SEED)
    }
}
